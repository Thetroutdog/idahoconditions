#!/usr/bin/env python3
"""Build src/data/idaho-rivers.json: main Idaho rivers as simplified lines in the same SVG space as idaho-map.json.

Source: Natural Earth 10m rivers (public domain), downloaded from GitHub on first run into /tmp/ic_rivers.
Only the rivers the activity catalog refers to are kept. Re-run only if the list or the map projection changes:
    python3 scripts/make_rivers.py
"""
import json, os, sys, urllib.request

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BASE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/"
CACHE = "/tmp/ic_rivers"
# (file, Natural Earth name) -> label shown on the map
WANTED = {
    # The plain lake_centerlines file holds only ~20 points of the Snake; the scale_rank file has the whole river.
    ("ne_10m_rivers_lake_centerlines_scale_rank.geojson", "Snake"): "Snake River",
    ("ne_10m_rivers_lake_centerlines.geojson", "Salmon"): "Salmon River",
    ("ne_10m_rivers_north_america.geojson", "Middle Fk.  Salmon"): "Middle Fork Salmon",
    ("ne_10m_rivers_north_america.geojson", "Clearwater"): "Clearwater River",
    ("ne_10m_rivers_north_america.geojson", "Lochsa"): "Lochsa River",
    ("ne_10m_rivers_north_america.geojson", "Selway"): "Selway River",
    ("ne_10m_rivers_north_america.geojson", "Saint Joe"): "St. Joe River",
    ("ne_10m_rivers_north_america.geojson", "Payette"): "Payette River",
    ("ne_10m_rivers_north_america.geojson", "Boise"): "Boise River",
    ("ne_10m_rivers_north_america.geojson", "Bruneau"): "Bruneau River",
    ("ne_10m_rivers_north_america.geojson", "Owyhee"): "Owyhee River",
    ("ne_10m_rivers_north_america.geojson", "Big Wood"): "Big Wood River",
    # Minor rivers: drawn for the statewide picture, never labeled.
    ("ne_10m_rivers_lake_centerlines_scale_rank.geojson", "Bear"): "Bear River",
    ("ne_10m_rivers_lake_centerlines_scale_rank.geojson", "Clark Fork"): "Clark Fork",
    ("ne_10m_rivers_lake_centerlines_scale_rank.geojson", "Pend Orielle"): "Pend Oreille River",
    ("ne_10m_rivers_north_america.geojson", "Priest"): "Priest River",
    ("ne_10m_rivers_north_america.geojson", "Kootenay"): "Kootenai River",
    ("ne_10m_rivers_north_america.geojson", "Big Lost"): "Big Lost River",
    ("ne_10m_rivers_north_america.geojson", "S.  Fk.  Boise"): "South Fork Boise River",
    ("ne_10m_rivers_north_america.geojson", "North Fork Payette"): "North Fork Payette River",
    ("ne_10m_rivers_north_america.geojson", "Middle Fk.  Clearwater"): "Middle Fork Clearwater River",
}
MINOR = {"Bear River", "Clark Fork", "Pend Oreille River", "Priest River", "Kootenai River", "Big Lost River",
         "South Fork Boise River", "North Fork Payette River", "Middle Fork Clearwater River"}


def get(fn):
    os.makedirs(CACHE, exist_ok=True)
    p = os.path.join(CACHE, fn)
    if not os.path.exists(p):
        urllib.request.urlretrieve(BASE + fn, p)
    return json.load(open(p))


def dp(pts, eps):
    """Douglas-Peucker line simplification."""
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    n = (dx * dx + dy * dy) ** 0.5 or 1e-9
    i, dmax = 0, 0
    for k in range(1, len(pts) - 1):
        d = abs(dy * pts[k][0] - dx * pts[k][1] + x2 * y1 - y2 * x1) / n
        if d > dmax:
            i, dmax = k, d
    if dmax > eps:
        return dp(pts[: i + 1], eps)[:-1] + dp(pts[i:], eps)
    return [pts[0], pts[-1]]


def main():
    m = json.load(open(os.path.join(ROOT, "src", "data", "idaho-map.json")))
    P = m["proj"]
    W, H = m["width"], m["height"]
    proj = lambda lon, lat: (P["pad"] + (lon - P["lon0"]) * P["k"] * P["s"], P["pad"] + (P["lat1"] - lat) * P["s"])
    out = []
    for fn in sorted({f for f, _ in WANTED}):
        for f in get(fn)["features"]:
            label = WANTED.get((fn, f["properties"].get("name")))
            if not label or not f["geometry"]:
                continue
            g = f["geometry"]
            lines = g["coordinates"] if g["type"] == "MultiLineString" else [g["coordinates"]]
            segs = []
            for ln in lines:
                pts = [proj(x, y) for x, y in ln]
                cur = []
                for x, y in pts:  # keep what is near the Idaho map; the page clips to the region outline
                    if -15 <= x <= W + 15 and -15 <= y <= H + 15:
                        cur.append((x, y))
                    elif cur:
                        segs.append(cur); cur = []
                if cur:
                    segs.append(cur)
            segs = [[[round(x, 1), round(y, 1)] for x, y in dp(s, 0.3)] for s in segs if len(s) > 1]
            if segs:
                out.append({"name": label, "segs": segs, **({"minor": True} if label in MINOR else {})})
    json.dump({"_note": "Generated by scripts/make_rivers.py from Natural Earth 10m rivers (public domain).", "rivers": out},
              open(os.path.join(ROOT, "src", "data", "idaho-rivers.json"), "w"), separators=(",", ":"))
    print("rivers:", [(r["name"], sum(len(s) for s in r["segs"])) for r in out])


if __name__ == "__main__":
    sys.exit(main())
